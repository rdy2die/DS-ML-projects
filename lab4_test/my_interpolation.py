"""Собственные реализации методов интерполяции.

Модуль содержит три метода:
    * linear_interp           - линейная (кусочно-линейная) интерполяция;
    * piecewise_quadratic_interp - кусочно-квадратичная интерполяция;
    * quadratic_interp        - квадратичная интерполяция по трём
                                ближайшим узлам.

Все функции принимают массивы узлов xs, ys (xs строго возрастает)
и точку (или массив точек) x, в которой нужно найти значение.
"""

import numpy as np


def _lagrange_quadratic(x, x0, x1, x2, y0, y1, y2):
    """Значение параболы, проходящей через три точки, в точке x.

    Используется интерполяционный многочлен Лагранжа 2-й степени:
        L(x) = y0*l0(x) + y1*l1(x) + y2*l2(x),
    где базисный многочлен li(x) равен 1 в узле xi и 0 в остальных.
    """
    l0 = (x - x1) * (x - x2) / ((x0 - x1) * (x0 - x2))
    l1 = (x - x0) * (x - x2) / ((x1 - x0) * (x1 - x2))
    l2 = (x - x0) * (x - x1) / ((x2 - x0) * (x2 - x1))
    return y0 * l0 + y1 * l1 + y2 * l2


def _segment_index(xs, x):
    """Номер i отрезка [xs[i], xs[i+1]], которому принадлежит x.

    np.searchsorted двоичным поиском находит место вставки x в xs.
    Результат ограничивается диапазоном [0, len(xs) - 2], чтобы
    крайние точки (x == xs[0] или x == xs[-1]) тоже попадали в отрезок.
    """
    i = np.searchsorted(xs, x, side="right") - 1
    return np.clip(i, 0, len(xs) - 2)


def linear_interp(xs, ys, x):
    """Линейная интерполяция.

    Соседние узлы соединяются отрезками прямых. Для x из
    [x_i, x_{i+1}]:
        y = y_i + (y_{i+1} - y_i) * (x - x_i) / (x_{i+1} - x_i)
    """
    i = _segment_index(xs, x)
    x0, x1 = xs[i], xs[i + 1]
    y0, y1 = ys[i], ys[i + 1]
    return y0 + (y1 - y0) * (x - x0) / (x1 - x0)


def piecewise_quadratic_interp(xs, ys, x):
    """Кусочно-квадратичная интерполяция.

    Узлы делятся на непересекающиеся тройки
    (x0, x1, x2), (x2, x3, x4), (x4, x5, x6), ...
    Соседние тройки имеют один общий узел. На каждом участке
    [x_{2k}, x_{2k+2}] строится своя парабола. Если число
    отрезков нечётное, последняя тройка берётся как
    (x_{n-3}, x_{n-2}, x_{n-1}), чтобы не выйти за массив.
    """
    if len(xs) < 3:
        raise ValueError("Нужно минимум 3 узла")
    i = _segment_index(xs, x)
    start = np.minimum(i - i % 2, len(xs) - 3)  # начало тройки (чётное)
    return _lagrange_quadratic(
        x, xs[start], xs[start + 1], xs[start + 2],
        ys[start], ys[start + 1], ys[start + 2],
    )


def quadratic_interp(xs, ys, x):
    """Квадратичная интерполяция по трём ближайшим узлам.

    Для каждой точки x выбираются три узла, ближайшие к ней:
    отрезок [x_i, x_{i+1}], содержащий x, и ещё один соседний узел
    с той стороны, которая ближе к x. Через них проводится парабола.
    В отличие от кусочно-квадратичной, тройка узлов «скользит»
    вместе с x, поэтому точность обычно выше.
    """
    if len(xs) < 3:
        raise ValueError("Нужно минимум 3 узла")
    i = _segment_index(xs, x)
    mid = (xs[i] + xs[i + 1]) / 2
    start = np.where(x < mid, i - 1, i)       # левый или правый сосед
    start = np.clip(start, 0, len(xs) - 3)    # не выходим за границы
    return _lagrange_quadratic(
        x, xs[start], xs[start + 1], xs[start + 2],
        ys[start], ys[start + 1], ys[start + 2],
    )


METHODS = {
    "Линейная": linear_interp,
    "Кусочно-квадратичная": piecewise_quadratic_interp,
    "Квадратичная (3 ближайших узла)": quadratic_interp,
}
